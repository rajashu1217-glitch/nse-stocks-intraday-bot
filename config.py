@dataclass
class BotConfig:
    # Timings (IST)
    STAGE1_PREMARKET_TIME: str = "08:55"
    PREOPEN_TIME: str = "09:07"
    SELECTION_TIME: str = "09:25"
    MARKET_OPEN_TIME: str = "09:15"
    PRICE_ACTION_START_TIME: str = "09:30"
    SQUAREOFF_TIME: str = "15:15"

    # Stage 1 (Pre-Market Sniper Shortlist) Rules
    STAGE1_MIN_STOCKS: int = 10
    STAGE1_MAX_STOCKS: int = 15
    NR4_LOOKBACK_DAYS: int = 4
    VOLUME_SURGE_LOOKBACK_DAYS: int = 20
    MIN_VOLUME_SURGE_RATIO: float = 1.3
    EXHAUSTION_STREAK_DAYS: int = 3
    ATR_PERIOD: int = 14

    # Stage 2 (09:07 + 09:25 Live Sniper Filter) Rules
    BREADTH_MISMATCH_MODE: str = os.getenv("BREADTH_MISMATCH_MODE", "skip")  # 'skip' or 'half_qty'
    TOP_SECTORS_COUNT: int = 3
    MIN_SECTOR_MOVE_PCT: float = 0.2
    SWEET_SPOT_MIN_PCT: float = 0.5
    SWEET_SPOT_MAX_PCT: float = 3.0
    MIN_RELATIVE_STRENGTH_PCT: float = 0.5
    OPENING_VOL_SURGE_MULT: float = 2.0
    TOP_OI_COUNT: int = 10
    FINAL_WATCHLIST_MAX: int = 2

    # Price Action Rules (5-Minute Timeframe)
    TIMEFRAME: str = "5m"
    IGNORE_FIRST_CANDLES: int = 3          # Ignore 09:15, 09:20, 09:25 candles
    MAX_ALERT_CANDLE_PCT: float = 0.5      # Alert candle range <= 0.5% of stock price
    SL_BUFFER_POINTS: float = 2.0          # Alert Low - 2 (Long) / Alert High + 2 (Short)
    TARGET_RR_RATIO: float = 2.0           # 1:2 Risk-to-Reward
    TARGET1_EXIT_RATIO: float = 0.50       # Book 50% at 1:2 RR, hold rest until 15:15
    MAX_TRADES_PER_DAY: int = int(os.getenv("MAX_TRADES_PER_DAY", "1"))

    # Paper Trading Sizing
    RISK_PER_TRADE_INR: float = float(os.getenv("RISK_PER_TRADE_INR", "1000"))
    MAX_CAPITAL_PER_TRADE_INR: float = float(os.getenv("MAX_CAPITAL_PER_TRADE_INR", "100000"))

    # Telegram
    TELEGRAM_BOT_TOKEN: str = os.getenv("TELEGRAM_BOT_TOKEN", "")
    TELEGRAM_CHAT_ID: str = os.getenv("TELEGRAM_CHAT_ID", "")
    TELEGRAM_ENABLED: bool = os.getenv("TELEGRAM_ENABLED", "True").lower() in ("true", "1", "yes")

    # Data Mode: 'live' or 'simulated'
    DATA_MODE: str = os.getenv("DATA_MODE", "live")

    # Files
    EXCEL_LOG_PATH: Path = BASE_DIR / "stocks_papertrade_log.xlsx"


config = BotConfig()
